def detect_category(message: str) -> str:
    msg = message.lower()
    msg = msg.replace("ة", "ه").replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")

    scores = {
        "greeting": sum(1 for p in GREETING_PATTERNS if p in msg),
        "attendance": sum(1 for p in ATTENDANCE_PATTERNS if p in msg),
        "salary": sum(1 for p in SALARY_PATTERNS if p in msg),
        "employee": sum(1 for p in EMPLOYEE_PATTERNS if p in msg),
        "task": sum(1 for p in TASK_PATTERNS if p in msg),
        "management": sum(1 for p in MANAGEMENT_PATTERNS if p in msg),
    }

    best = max(scores, key=scores.get)
    if scores[best] == 0:
        return "default"
    return best


def generate_contextual_response(message: str, user: dict, company: dict, history: list) -> str:
    category = detect_category(message)
    responses = AI_RESPONSES.get(category, AI_RESPONSES["default"])
    base = random.choice(responses)

    user_name = user.get("name", "")
    company_name = company.get("name", "") if company else ""
    role = "المدير" if user.get("role") == "manager" else "الموظف"

    # Personalize greeting
    if category == "greeting":
        if user_name:
            base = base.replace("أهلاً وسهلاً!", f"أهلاً {user_name}!")
            base = base.replace("مرحباً!", f"مرحباً {user_name}!")
            base = base.replace("أهلاً بيك!", f"أهلاً بيك {user_name}!")
        if company_name:
            base += f"\n\nشركة **{company_name}** — أنا هنا لخدمتك! 🚀"

    # Add role-specific tip
    if role == "الموظف" and category not in ["greeting", "default"]:
        base += "\n\n💬 *للمزيد من التفاصيل تحدّث مع مديرك مباشرةً.*"

    return base


